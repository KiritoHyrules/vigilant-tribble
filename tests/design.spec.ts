import { test, expect, type Page } from "@playwright/test"
import AxeBuilder from "@axe-core/playwright"

async function enter(page: Page) {
  await page.goto("/")
  await page.getByRole("button", { name: "Acceder al sistema", exact: true }).click()
  await page.getByLabel("Usuario de demostración", { exact: true }).fill("demo.analista")
  await page.getByLabel("Contraseña de demostración", { exact: true }).fill("trasu-demo")
  await page.getByRole("button", { name: "Entrar a la demostración", exact: true }).click()
  await page.getByRole("button", { name: "Ahora no", exact: true }).click()
}

test("diseño: bandeja, detalle y guía localizable sin ejecutar acciones", async ({ page }, info) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  await enter(page)
  await expect(page.getByRole("button", { name: "Probar error", exact: true })).toBeHidden()
  await page.getByText("Simular estados", { exact: true }).click()
  await expect(page.getByRole("button", { name: "Probar error", exact: true })).toBeVisible()
  await page.getByText("Simular estados", { exact: true }).click()
  await page.screenshot({ path: `.impeccable/review/workspace-${info.project.name}.png`, fullPage: true })
  let results = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze()
  expect(results.violations.map((v) => ({ id: v.id, targets: v.nodes.map((n) => n.target) }))).toEqual([])
  await page.getByRole("button", { name: "Ayuda y guías", exact: true }).click()
  const help = page.getByRole("dialog", { name: "Ayuda y guías", exact: true })
  await help.getByRole("button", { name: /Abrir un expediente y elegir cómo continuar/ }).click()
  await help.getByRole("button", { name: "Acompañarme en esta tarea", exact: true }).click()
  const companion = page.getByRole("complementary", { name: "Guía durante la tarea" })
  await expect(companion).toContainText("Paso 1 de 4")
  await companion.getByRole("button", { name: "Mostrar en pantalla", exact: true }).click()
  await expect(page.locator('[data-guided="true"]')).toBeFocused()
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("Pendientes y seguimiento")
  await page.locator('[data-guided="true"]').click()
  await expect(companion).toContainText("Paso 2 de 4")
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("DEMO-TRASU-001")
  await companion.getByRole("button", { name: "Pausar guía", exact: true }).click()
  await expect(page.locator('[data-guided="true"]')).toHaveCount(0)
  await expect(companion).toContainText("Guía en pausa")
  await companion.getByRole("button", { name: "Reanudar guía", exact: true }).click()
  await expect(page.locator('[data-guided="true"]')).toHaveCount(1)
  await companion.getByRole("button", { name: "Siguiente paso", exact: true }).click()
  await companion.getByRole("button", { name: "Mostrar en pantalla", exact: true }).click()
  await expect(page.getByRole("button", { name: "Abrir documentos y versiones", exact: true })).toBeFocused()
  await expect(page.getByRole("heading", { level: 1 })).toHaveText("DEMO-TRASU-001")
  // Return to the top of the workspace for comparable screenshots, without changing app state.
  await companion.scrollIntoViewIfNeeded()
  await page.screenshot({ path: `.impeccable/review/guided-${info.project.name}.png`, fullPage: true })
  results = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze()
  expect(results.violations.map((v) => ({ id: v.id, targets: v.nodes.map((n) => n.target) }))).toEqual([])
  await companion.getByRole("button", { name: "Cerrar guía de tarea", exact: true }).click()
  await expect(page.locator('[data-guided="true"]')).toHaveCount(0)
  await page.getByRole("heading", { level: 1 }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `.impeccable/review/detail-${info.project.name}.png`, fullPage: true })
  expect(errors).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
